# Windows counterpart of setup.sh: wires PowerShell 7 (pwsh) up to this repo. Must stay
# idempotent. install.ps1 runs it with pwsh on a fresh machine.
#Requires -Version 7.4
[CmdletBinding()]
param(
  # Only rewrite the profile wrappers; used by the daily update.
  [switch]$SkipInstall
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'powershell\common.ps1')

# First line of every file setup.ps1 writes. Files without it are backed up before replacing.
$ManagedFileHeader = '# Generated by ~/.dotfiles/setup.ps1.'

function Get-ProfilePath {
  $documents = [Environment]::GetFolderPath('MyDocuments')
  return (Join-Path $documents 'PowerShell\Microsoft.PowerShell_profile.ps1')
}

# Earlier versions also wired Windows PowerShell 5.1. The shared profile is pwsh-only now, so
# drop that wrapper. Only a file this script wrote is removed; a hand-written one stays.
function Remove-WindowsPowerShellWrapper {
  param(
    [string]$ProfilePath = (Join-Path ([Environment]::GetFolderPath('MyDocuments')) `
      'WindowsPowerShell\Microsoft.PowerShell_profile.ps1')
  )
  if (-not (Test-Path -LiteralPath $ProfilePath)) { return }
  if ([IO.File]::ReadAllText($ProfilePath).StartsWith($ManagedFileHeader)) {
    Remove-Item -LiteralPath $ProfilePath
  }
}

# The PowerShell counterpart of the ~/.zshrc sourcing wrapper.
function Get-ProfileWrapper {
  param([Parameter(Mandatory)][string]$DotfilesDir)
  $profileScript = (Join-Path $DotfilesDir 'powershell\profile.ps1').Replace("'", "''")
  return @(
    "$ManagedFileHeader Local changes go in ~/.pwsh_pre.ps1 or ~/.pwsh_post.ps1."
    'if (Test-Path "$HOME\.pwsh_pre.ps1") { . "$HOME\.pwsh_pre.ps1" }'
    ". '$profileScript'"
    'if (Test-Path "$HOME\.pwsh_post.ps1") { . "$HOME\.pwsh_post.ps1" }'
    ''
  ) -join "`r`n"
}

function Write-ManagedFile {
  param(
    [Parameter(Mandatory)][string]$Path,
    [Parameter(Mandatory)][string]$Content
  )
  if (Test-Path -LiteralPath $Path) {
    $current = [IO.File]::ReadAllText($Path)
    if ($current -eq $Content) { return }
    # A file this script did not write: keep it, like ensure_symlink does.
    if (-not $current.StartsWith($ManagedFileHeader)) {
      Move-Item -LiteralPath $Path -Destination "$Path.bak" -Force
    }
  } else {
    $null = New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path)
  }
  [IO.File]::WriteAllText($Path, $Content)
}

function Write-ProfileWrapper {
  param(
    [Parameter(Mandatory)][string]$ProfilePath,
    [Parameter(Mandatory)][string]$DotfilesDir
  )
  Write-ManagedFile -Path $ProfilePath -Content (Get-ProfileWrapper -DotfilesDir $DotfilesDir)
}

# Where Ghostty on Windows looks for its config (XDG_CONFIG_HOME, else LOCALAPPDATA).
function Get-GhosttyConfigPath {
  $base = if ($env:XDG_CONFIG_HOME) { $env:XDG_CONFIG_HOME } else { $env:LOCALAPPDATA }
  return (Join-Path $base 'ghostty\config.ghostty')
}

# Ghostty has no per-OS conditionals, so Windows gets a wrapper that includes the shared
# config, then the Windows one, then an optional machine-local file.
function Get-GhosttyWrapper {
  param([Parameter(Mandatory)][string]$DotfilesDir)
  $ghostty = Join-Path $DotfilesDir 'ghostty'
  return @(
    "$ManagedFileHeader Local changes go in config.local next to this file."
    "config-file = `"$(Join-Path $ghostty 'config')`""
    "config-file = `"$(Join-Path $ghostty 'windows')`""
    'config-file = ?config.local'
    ''
  ) -join "`r`n"
}

function Write-GhosttyWrapper {
  param(
    [Parameter(Mandatory)][string]$ConfigPath,
    [Parameter(Mandatory)][string]$DotfilesDir
  )
  Write-ManagedFile -Path $ConfigPath -Content (Get-GhosttyWrapper -DotfilesDir $DotfilesDir)
}

function Get-StartupShortcutPath {
  return (Join-Path ([Environment]::GetFolderPath('Startup')) 'init.ahk.lnk')
}

# Run init.ahk at logon. Rewrites the shortcut only when it points somewhere else.
function Write-AutoHotkeyStartup {
  param(
    [Parameter(Mandatory)][string]$ShortcutPath,
    [Parameter(Mandatory)][string]$AutoHotkey,
    [Parameter(Mandatory)][string]$Script
  )
  $shell = New-Object -ComObject WScript.Shell
  $arguments = "`"$Script`""
  if (Test-Path -LiteralPath $ShortcutPath) {
    $existing = $shell.CreateShortcut($ShortcutPath)
    if ($existing.TargetPath -eq $AutoHotkey -and $existing.Arguments -eq $arguments) { return }
    Write-Host "Replacing startup shortcut to $($existing.TargetPath) $($existing.Arguments)"
  }
  $shortcut = $shell.CreateShortcut($ShortcutPath)
  $shortcut.TargetPath = $AutoHotkey
  $shortcut.Arguments = $arguments
  $shortcut.WorkingDirectory = Split-Path -Parent $Script
  $shortcut.Description = 'Window management from ~/.dotfiles/init.ahk'
  $shortcut.Save()
}

# /restart replaces a running copy of the same script, so changes to init.ahk apply now.
function Start-AutoHotkey {
  param(
    [Parameter(Mandatory)][string]$AutoHotkey,
    [Parameter(Mandatory)][string]$Script
  )
  Start-Process -FilePath $AutoHotkey -ArgumentList @('/restart', "`"$Script`"")
}

function Set-AutoHotkeyStartup {
  param([Parameter(Mandatory)][string]$DotfilesDir)
  $autoHotkey = Find-AutoHotkey
  if (-not $autoHotkey) {
    Write-Warning 'AutoHotkey v2 is not installed; skipping init.ahk.'
    return
  }
  $script = Join-Path $DotfilesDir 'init.ahk'
  Write-AutoHotkeyStartup -ShortcutPath (Get-StartupShortcutPath) `
    -AutoHotkey $autoHotkey -Script $script
  Start-AutoHotkey -AutoHotkey $autoHotkey -Script $script
}

function Write-LocalProfiles {
  foreach ($name in '.pwsh_pre.ps1', '.pwsh_post.ps1') {
    $path = Join-Path $HOME $name
    if (-not (Test-Path -LiteralPath $path)) { [IO.File]::WriteAllText($path, '') }
  }
}

# Pick up PATH changes from installers without restarting the shell.
function Update-SessionPath {
  $env:Path = @(
    [Environment]::GetEnvironmentVariable('Path', 'Machine'),
    [Environment]::GetEnvironmentVariable('Path', 'User')
  ) -join ';'
}

function Install-WingetPackages {
  foreach ($package in $DotfilesWingetPackages) {
    if (Test-DotfilesPackageInstalled -Package $package) { continue }
    Write-Host "Installing $($package.Id)..."
    & winget install --id $package.Id --exact --silent --disable-interactivity `
      --accept-package-agreements --accept-source-agreements
    if ($LASTEXITCODE -ne 0) { Write-Warning "Failed to install $($package.Id)." }
  }
  Update-SessionPath
}

function Install-Modules {
  foreach ($module in $DotfilesModules) {
    $installed = Get-Module -ListAvailable $module.Name |
      Where-Object { $_.Version -ge $module.MinimumVersion }
    if ($installed) { continue }
    Write-Host "Installing module $($module.Name)..."
    # PSResourceGet ships with PowerShell 7.4+; no NuGet provider bootstrap needed. Name the
    # repository: the Microsoft Artifact Registry outranks PSGallery and answers Not Found.
    Install-PSResource -Name $module.Name -Repository PSGallery -Scope CurrentUser `
      -TrustRepository -Quiet
  }
}

# .p10k.zsh and ghostty/config expect MesloLGM Nerd Font.
function Install-NerdFont {
  $fontDirs = @(
    (Join-Path $env:WINDIR 'Fonts'),
    (Join-Path $env:LOCALAPPDATA 'Microsoft\Windows\Fonts')
  )
  $found = Get-ChildItem -Path $fontDirs -Filter 'MesloLGM*Nerd*' -ErrorAction SilentlyContinue
  if ($found) { return }
  if (-not (Get-Command oh-my-posh -ErrorAction SilentlyContinue)) { return }
  Write-Host 'Installing Meslo Nerd Font...'
  & oh-my-posh font install Meslo
}

# Share .gitconfig with macOS and Linux, like ensure_git_config in setup.sh. Adds the include
# only when it is missing, so other include.path entries are kept.
function Set-GitInclude {
  param([Parameter(Mandatory)][string]$DotfilesDir)
  if (-not (Get-Command git -ErrorAction SilentlyContinue)) { return }
  $path = (Join-Path $DotfilesDir '.gitconfig').Replace('\', '/')
  $existing = @(& git config --global --get-all include.path 2>$null)
  if ($existing -contains $path) { return }
  & git config --global --add include.path $path
}

# The profile is a local script, so the Windows default of Restricted would block it.
function Set-ProfileExecutionPolicy {
  $policy = Get-ExecutionPolicy -Scope CurrentUser
  if ($policy -in 'Undefined', 'Restricted', 'AllSigned') {
    if ((Get-ExecutionPolicy -Scope LocalMachine) -in 'RemoteSigned', 'Unrestricted', 'Bypass') {
      return
    }
    Set-ExecutionPolicy -Scope CurrentUser -ExecutionPolicy RemoteSigned -Force
  }
}

function Invoke-Setup {
  param([string]$DotfilesDir = $PSScriptRoot)
  Write-ProfileWrapper -ProfilePath (Get-ProfilePath) -DotfilesDir $DotfilesDir
  Remove-WindowsPowerShellWrapper
  Write-LocalProfiles
  Write-GhosttyWrapper -ConfigPath (Get-GhosttyConfigPath) -DotfilesDir $DotfilesDir
  Set-GitInclude -DotfilesDir $DotfilesDir
  # No core.hooksPath here: hooks/pre-push runs `make check`, which needs make and shellspec.
  if (-not $SkipInstall) {
    Set-ProfileExecutionPolicy
    if (Get-Command winget -ErrorAction SilentlyContinue) {
      Install-WingetPackages
    } else {
      Write-Warning 'winget is missing; install oh-my-posh, fzf, and AutoHotkey yourself.'
    }
    Install-Modules
    Install-NerdFont
  }
  # Also on -SkipInstall, so the daily update restarts AutoHotkey with the new init.ahk.
  Set-AutoHotkeyStartup -DotfilesDir $DotfilesDir
}

# Tests dot-source this file to get the functions without running setup.
if ($MyInvocation.InvocationName -ne '.') {
  Invoke-Setup
}
