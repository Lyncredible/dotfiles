#!/bin/sh
# shellcheck disable=SC2034,SC2059

set -e

init_colors() {
  TPUT_BIN="${TPUT_BIN:-tput}"
  if command -v "$TPUT_BIN" >/dev/null 2>&1; then
    ncolors=$("$TPUT_BIN" colors 2>/dev/null || true)
  fi

  if [ -t 1 ] && [ -n "${ncolors:-}" ] && [ "${ncolors:-0}" -ge 8 ]; then
    RED=$("$TPUT_BIN" setaf 1)
    GREEN=$("$TPUT_BIN" setaf 2)
    YELLOW=$("$TPUT_BIN" setaf 3)
    BLUE=$("$TPUT_BIN" setaf 4)
    BOLD=$("$TPUT_BIN" bold)
    NORMAL=$("$TPUT_BIN" sgr0)
  else
    RED=""
    GREEN=""
    YELLOW=""
    BLUE=""
    BOLD=""
    NORMAL=""
  fi
}

set_defaults() {
  DOTFILES_DIR="${DOTFILES_DIR:-$HOME/.dotfiles}"
  CONFIG_DIR="${CONFIG_DIR:-$HOME/.config}"
  ANTIGEN_DIR="${ANTIGEN_DIR:-$HOME/.antigen}"
  GIT_BIN="${GIT_BIN:-git}"
  GREP_BIN="${GREP_BIN:-grep}"
  ZSH_BIN="${ZSH_BIN:-zsh}"
  CHSH_BIN="${CHSH_BIN:-chsh}"
  SKIP_CHSH="${SKIP_CHSH:-0}"
  UNAME_BIN="${UNAME_BIN:-uname}"
}

write_zsh_wrapper() {
  # Migrate .zshrc_local → .zshrc_post
  if [ -e "$HOME/.zshrc_local" ] && [ ! -e "$HOME/.zshrc_post" ]; then
    mv "$HOME/.zshrc_local" "$HOME/.zshrc_post"
  fi

  cat > "$HOME/.zshrc" <<'EOF'
[[ -f ~/.zshrc_pre ]] && source ~/.zshrc_pre
source ~/.dotfiles/.zshrc
[[ -f ~/.zshrc_post ]] && source ~/.zshrc_post
EOF

  [ -e "$HOME/.zshrc_pre" ] || touch "$HOME/.zshrc_pre"
  [ -e "$HOME/.zshrc_post" ] || touch "$HOME/.zshrc_post"
}

ensure_symlink() {
  target="$1"
  link_path="$2"
  # Already correct
  if [ -L "$link_path" ] && [ "$(readlink "$link_path")" = "$target" ]; then
    return 0
  fi
  # Wrong symlink, broken symlink, or real file — back up and replace
  if [ -e "$link_path" ] || [ -L "$link_path" ]; then
    mv "$link_path" "${link_path}.bak"
  fi
  ln -s "$target" "$link_path"
}

ensure_dir() {
  dir_path="$1"
  if [ ! -d "$dir_path" ]; then
    mkdir "$dir_path"
  fi
}

ensure_git_config() {
  "$GIT_BIN" config --global include.path "$DOTFILES_DIR/.gitconfig"
}

ensure_git_hooks_path() {
  "$GIT_BIN" -C "$DOTFILES_DIR" config core.hooksPath hooks
}

ensure_antigen() {
  if [ ! -d "$ANTIGEN_DIR" ]; then
    echo "${BLUE}Installing antigen...${NORMAL}"
    "$GIT_BIN" clone https://github.com/zsh-users/antigen.git "$ANTIGEN_DIR"
  fi
}

resolve_zsh_path() {
  command -v "$ZSH_BIN"
}

ensure_login_shell() {
  if [ "$SKIP_CHSH" = "1" ]; then
    return
  fi

  zsh_path=$(resolve_zsh_path)
  if [ "$zsh_path" != "$SHELL" ]; then
    "$CHSH_BIN" -s "$zsh_path"
  fi
}

ensure_local_bin() {
  local_bin="$HOME/.local/bin"
  ensure_dir "$HOME/.local"
  ensure_dir "$local_bin"
  for script in "$DOTFILES_DIR/.local/bin"/*; do
    [ -f "$script" ] || continue
    ensure_symlink "$script" "$local_bin/$(basename "$script")"
  done
}

GHOSTTY_WRAPPER_HEADER='# Generated by ~/.dotfiles/setup.sh.'

# Move a Ghostty config aside unless this script wrote it.
backup_unmanaged_ghostty_config() {
  config_path="$1"
  [ -f "$config_path" ] || return 0
  first_line=""
  IFS= read -r first_line < "$config_path" || true
  case "$first_line" in
    "$GHOSTTY_WRAPPER_HEADER"*) ;;
    *) mv "$config_path" "${config_path}.bak" ;;
  esac
}

# Ghostty has no per-OS config conditionals, so ~/.config/ghostty holds a wrapper that
# includes the shared config, then ghostty/macos or ghostty/linux, then an optional
# config.local. setup.ps1 writes the Windows equivalent.
write_ghostty_wrapper() {
  ghostty_dir="$CONFIG_DIR/ghostty"
  if [ "$("$UNAME_BIN" -s)" = "Darwin" ]; then
    ghostty_os=macos
  else
    ghostty_os=linux
  fi
  # Older setups linked the whole directory to the repo; replace the link, not its target.
  if [ -L "$ghostty_dir" ]; then
    rm "$ghostty_dir"
  fi
  ensure_dir "$ghostty_dir"
  # Ghostty loads the legacy `config` too, so a stray one would apply before the includes.
  backup_unmanaged_ghostty_config "$ghostty_dir/config"
  backup_unmanaged_ghostty_config "$ghostty_dir/config.ghostty"
  cat > "$ghostty_dir/config.ghostty" <<EOF
$GHOSTTY_WRAPPER_HEADER Local changes go in config.local next to this file.
config-file = "$DOTFILES_DIR/ghostty/config"
config-file = "$DOTFILES_DIR/ghostty/$ghostty_os"
config-file = ?config.local
EOF
}

CLAUDE_MD_HEADER='<!-- Generated by ~/.dotfiles/setup.sh. Add local instructions below. -->'

# A directory the repo used to track with only a .gitkeep in it can go; anything else is kept.
remove_placeholder_dir() {
  dir_path="$1"
  [ -d "$dir_path" ] && [ ! -L "$dir_path" ] || return 0
  rm -f "$dir_path/.gitkeep"
  rmdir "$dir_path" 2>/dev/null || true
}

# ~/.claude is Claude Code's own directory: its login, history and transcripts stay here,
# out of the repo. Only what this repo shares is wired in: CLAUDE.md as an @import (no
# link needed), and agents/ and rules/ as links. setup.ps1 does the same on Windows;
# main.zshrc merges claude/settings.json into ~/.claude/settings.json.
ensure_claude_config() {
  claude_dir="$HOME/.claude"
  # Older setups linked all of ~/.claude to the repo's .claude. Move that state back here.
  if [ -L "$claude_dir" ]; then
    old_target="$(readlink "$claude_dir")"
    if [ "$old_target" = "$DOTFILES_DIR/.claude" ] && [ -d "$old_target" ]; then
      rm "$claude_dir"
      mv "$old_target" "$claude_dir"
    else
      mv "$claude_dir" "$claude_dir.bak"
    fi
  fi
  ensure_dir "$claude_dir"

  claude_md="$claude_dir/CLAUDE.md"
  first_line=""
  [ -f "$claude_md" ] && { IFS= read -r first_line < "$claude_md" || true; }
  if [ "$first_line" != "$CLAUDE_MD_HEADER" ]; then
    [ -e "$claude_md" ] && mv "$claude_md" "$claude_md.bak"
    # Spaces in an @import path are escaped with a backslash.
    import_path="$(printf '%s' "$DOTFILES_DIR/claude/CLAUDE.md" | sed 's/ /\\ /g')"
    printf '%s\n@%s\n' "$CLAUDE_MD_HEADER" "$import_path" > "$claude_md"
  fi

  for name in agents rules; do
    remove_placeholder_dir "$claude_dir/$name"
    ensure_symlink "$DOTFILES_DIR/claude/$name" "$claude_dir/$name"
  done
}

ensure_agent_skills() {
  target_dir="$HOME/.agents/skills"
  ensure_dir "$HOME/.agents"
  ensure_dir "$target_dir"
  for skill in "$DOTFILES_DIR/.agents/skills"/*/; do
    [ -d "$skill" ] || continue
    ensure_symlink "$skill" "$target_dir/$(basename "$skill")"
  done
  ensure_symlink "$target_dir" "$HOME/.claude/skills"
}

main() {
  init_colors
  set_defaults
  write_zsh_wrapper
  ensure_symlink "$DOTFILES_DIR/.p10k.zsh" "$HOME/.p10k.zsh"
  ensure_git_config
  ensure_git_hooks_path
  ensure_symlink "$DOTFILES_DIR/.vimrc" "$HOME/.vimrc"
  ensure_symlink "$DOTFILES_DIR/.tmux.conf" "$HOME/.tmux.conf"
  ensure_symlink "$DOTFILES_DIR/.hammerspoon" "$HOME/.hammerspoon"
  ensure_dir "$CONFIG_DIR"
  ensure_symlink "$DOTFILES_DIR/karabiner" "$CONFIG_DIR/karabiner"
  write_ghostty_wrapper
  ensure_claude_config
  ensure_local_bin
  ensure_agent_skills
  ensure_antigen
  ensure_login_shell
}

main "$@"
